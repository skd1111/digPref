def base_title(title: str) -> str:
    """去掉标题里的版本括号（含年份）与空白，便于同名归并。"""
    t = re.sub(r"[（(][^（()）]*[)）]", "", title or "").strip()
    t = re.sub(r"（\d{4}）$", "", t)
    return re.sub(r"\s+", "", t)


def dedup_key(title: str) -> str:
    """归一化标题：去括号与末尾年份，同名多版本归为一键。"""
    t = base_title(title)
    t = re.sub(r"\d{4}$", "", t)
    return t


def _hit(patterns: list[str], text: str) -> bool:
    return any(re.search(p, text) for p in patterns)


def _judicial_hit(text: str) -> bool:
    return any(p in text for p in JUDICIAL_KEEP if not p.startswith("^"))


def pick_domain(meta: dict) -> str | None:
    """返回该文档所属域；不属于任何域返回 None。"""
    title = meta.get("title") or ""
    link = meta.get("LinkTitle") or ""
    group = meta.get("group") or ""
    blob = base_title(title) + " " + base_title(link)
    if _judicial_hit(title + link) or _judicial_hit(blob):
        return "05_司法解释"
    for domain, rules in DOMAINS.items():
        if _hit(rules.get("exclude", []), blob):
            continue
        if _hit(rules["include"], blob):
            return domain
    return None


def eligible(meta: dict) -> bool:
    """效力状态与层级过滤。"""
    if meta.get("status") not in STATUS_KEEP:
        return False
    group = meta.get("group") or ""
    if group in GROUPS_KEEP:
        return True
    return group == "司法解释" and _judicial_hit((meta.get("title") or "") + (meta.get("LinkTitle") or ""))


def best_versions_per_base(rows: list[dict]) -> list[dict]:
    """同一部法规（或同名司法解释）只保留最新一版。"""
    grouped: dict[str, list[dict]] = {}
    for r in rows:
        grouped.setdefault(dedup_key(r["title"]), []).append(r)
    out = []
    for rows_ in grouped.values():
        rows_.sort(key=lambda r: (r["date"], r["status"] == "有效", r["size"]), reverse=True)
        out.append(rows_[0])
    return out
